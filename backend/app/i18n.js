function getLanguage() {
  try {
    const stored = localStorage.getItem("sip_language");
    if (stored && I18N[stored]) return stored;
  } catch (error) {
    // localStorage unavailable; fall back to default below
  }
  return "en";
}

function setLanguage(language) {
  if (!I18N[language]) return;
  try {
    localStorage.setItem("sip_language", language);
  } catch (error) {
    // ignore storage failures, language just won't persist
  }
  document.documentElement.lang = language;
  applyTranslations();
}

function t(key, vars) {
  const language = getLanguage();
  let value = (I18N[language] && I18N[language][key]) ?? I18N.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, replacement]) => {
      value = value.replace(`{${name}}`, replacement);
    });
  }
  return value;
}

function applyTranslations() {
  // Also on page load, so screen readers use the right pronunciation.
  document.documentElement.lang = getLanguage();
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });
  const switcher = document.querySelector("#language-switcher");
  if (switcher) switcher.value = getLanguage();
}
